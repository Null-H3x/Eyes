    ("West 1","East 1",0),("East 2","East 1",77),("East 5","East 4",0),
    ("West 4","East 4",54),("West 3","East 3",54),           # FR32
    ("East 3","East 1",52),("West 3","East 1",23),("East 4","East 1",53), # FR192
    ("West 2","East 1",39),                                   # FR178
