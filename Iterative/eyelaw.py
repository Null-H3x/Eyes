# ---------------------------------------------------------------- engine
def inv(x): return pow(x % N, -1, N)

def tier1(vec, f):
    """single-rho ratio consistency; returns (verdict, detail)."""
    rhos, k = set(), 0
    for a, b in itertools.combinations(sorted(vec), 2):
        df, dv = (f[a]-f[b]) % N, (vec[a]-vec[b]) % N
        if df == 0:
            if dv != 0: return ("REFUTED", "zero-Df pair with nonzero Db")
            continue
        k += 1; rhos.add(dv * inv(df) % N)
    if k < 3: return ("UNDERDETERMINED", f"{k} informative pairs")
    return (("HIT", f"rho={rhos.pop()} over {k} pairs") if len(rhos) == 1
            else ("REFUTED", f"{len(rhos)} distinct rho over {k} pairs"))

def tier2(vec1, f):
    """b_true = f exactly: d = Df * Db1^-1 single-valued; returns verdict."""
    ds, k = set(), 0
    for a, b in itertools.combinations(sorted(vec1), 2):
        df, dv = (f[a]-f[b]) % N, (vec1[a]-vec1[b]) % N
        if dv == 0:
            if df != 0: return ("REFUTED", "zero-Db1 pair with nonzero Df")
            continue
        k += 1; ds.add(df * inv(dv) % N)
    if k < 3: return ("UNDERDETERMINED", f"{k} informative pairs")
    if len(ds) == 1:
        d = ds.pop()
        return (("HIT", f"d={d} over {k} pairs") if d != 0
                else ("REFUTED", "d=0"))
    return ("REFUTED", f"{len(ds)} distinct d over {k} pairs")

def fold(x): x %= N; return min(x, N - x)

def stats(vec):
    ds = [fold(vec[a]-vec[b]) for a, b in itertools.combinations(sorted(vec), 2)]
    return len(set(ds)), sum(1 for x in ds if x == 0)

# ---------------------------------------------------------------- gates
def gates():
    ok = True
    def chk(name, cond, note=""):
        nonlocal ok; ok &= bool(cond)
        print(f"  [{'PASS' if cond else 'FAIL'}] {name} {note}")
    # G1 planted tier-1 law is found, and only by its own f
    plant = {m: (7*LEN[m] + 3) % N for m in MSGS}
    hits = [nm for nm, f in F_LAWS.items() if tier1(plant, f)[0] == "HIT"]
    chk("planted rho=7 length-law detected, uniquely", hits == ["F3 message length"],
        f"(hits: {hits})")
    # G2 shuffled-f rejection
    rng = random.Random(4194); false = 0
    vals = [LEN[m] for m in MSGS]
    for _ in range(500):
        sh = vals[:]; rng.shuffle(sh)
        if tier1(plant, dict(zip(MSGS, sh)))[0] == "HIT": false += 1
    chk("shuffled-f false-hit rate 0/500", false == 0, f"({false}/500)")
    # G3 planted tier-2 recovers d
    d = 37; b1 = {m: (LEN[m]-LEN["East 1"]) * inv(d) % N for m in MSGS}
    v, det = tier2(b1, LEN)
    chk("planted tier-2 recovers d=37", v == "HIT" and "d=37" in det, f"({det})")
    # G4 corruption refutes
    bad = dict(plant); bad["West 4"] = (bad["West 4"]+1) % N
    chk("one corrupted value kills the law",
        tier1(bad, F_LAWS["F3 message length"])[0] == "REFUTED")
    # G5 statistic sanity
    Dp, _ = stats(plant); Du, _ = stats({m: rng.randrange(N) for m in MSGS})
    chk("MC statistic separates plant from uniform draw", Dp < Du, f"(D {Dp} vs {Du})")
    # G6 assembled vector reproduces every published difference
    bad = [(m2, m1, v) for m2, m1, v in PUBLISHED_DIFFS
           if (B1[m2]-B1[m1]) % N != v % N]
    chk("b-vector reproduces all 9 published diffs", not bad, f"(fail: {bad})")
    # G7 corpus cross-check when available
    cj = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "Eyes-main", "noita_eye_core", "corpus.json")
    if os.path.exists(cj):
        c = json.load(open(cj)); rows = dict(zip(c["message_labels"], c["ciphertexts"]))
        chk("c0/lengths match corpus.json",
            all(rows[m][0] == C0[m] and len(rows[m]) == LEN[m] for m in MSGS))
        chk("stamped header uniform (c1 identical x9) -> header laws excluded",
            len({rows[m][1] for m in MSGS}) == 1)
    if not ok: raise SystemExit(f"{XD}: GATE FAILURE -- results below are void")
    print("  gates: ALL GREEN")

# ---------------------------------------------------------------- run
