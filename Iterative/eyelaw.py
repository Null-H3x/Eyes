XD = "XD-MBYG04K-URS3LF"; N = 83
MSGS = ["East 1","West 1","East 2","West 2","East 3","West 3","East 4","West 4","East 5"]

# ---------------------------------------------------------------- data
B1 = {"East 1":0,"West 1":0,"East 2":77,"West 2":39,"East 3":52,
      "West 3":23,"East 4":53,"West 4":24,"East 5":53}          # drift-1 units
P0 = {"East 1":0,"East 2":63,"East 3":54,"West 3":30,"East 4":23} # drift-1 units
